package LearningBasics;

public class MulDiv {
    public static void main(String... args){
        int a=10;
        int b=3;
        int mul=a*b;
        float div=a/b;
        int mod=a%b;
        System.out.println("Multiplication "+mul);
        System.out.println("Division "+ div);
        System.out.print("Remainder "+mod);
    }
}
